"""분류 경계에 걸치는 질문을 돌려 본다. 채점하지 않는다 — 어디로 가는지 보는 것이 목적이다.

    python probe_ambiguous.py

평가셋 12건은 카테고리가 깔끔하게 갈리는 문항만 있다. 실제 문의는 두 영역에 걸친다.
"""
import agent

CASES = [
    ("악어가죽 지갑도 800달러 안에 들어가면 그냥 가져올 수 있나요?",
     "멸종위기종 ↔ 면세  — 금액 이야기를 하지만 핵심은 CITES 허가다"),
    ("입국장면세점에서 산 위스키도 술 면세 한도에 포함되나요?",
     "면세점 ↔ 면세  — 산 곳은 면세점, 묻는 것은 주류 한도"),
    ("독일 소시지 30달러어치 샀는데 면세 한도 안이면 괜찮죠?",
     "면세 ↔ 검역  — 금액은 상관없고 검역이 막는다"),
    ("캐비어를 선물로 받았는데 가져올 수 있나요?",
     "검역 ↔ 멸종위기종  — 식품이면서 철갑상어(CITES)다"),
    ("화장품에 사향 성분이 들어있다는데 문제 될까요?",
     "멸종위기종 ↔ 면세  — 일반 화장품처럼 들리지만 CITES 성분이다"),
    ("해외 쇼핑몰에서 주문해서 택배로 받는 술은 몇 병까지 되나요?",
     "면세 ↔ 범위밖  — 해외직구(발송)는 이 봇의 범위가 아니다"),
    ("반려견을 데리고 입국하려면 뭐가 필요한가요?",
     "검역 ↔ 범위밖  — 기념품은 아니지만 동물검역 문서에 있다"),
    ("면세 한도 넘은 걸 공항에서 그냥 버리고 나와도 되나요?",
     "면세 ↔ 범위밖  — 폐기 절차는 우리 문서에 없다"),
]


def main():
    for i, (q, why) in enumerate(CASES, 1):
        s = agent.run(q)
        print(f"\n{'=' * 78}\n[{i}] {q}\n    걸치는 지점: {why}")
        print(f"    분류: {s['category']}   도구: {s['tools_called'] or '없음 (넘김)'}"
              f"   검증: {'위반 ' + str(s['violations']) if s['violations'] else '통과'}")
        for e in s["evidence"]:
            print(f"      근거: {'보조' if e['보조'] else '규정'} · {e['제목'][:52]}")
        print(f"\n{s['answer']}")


if __name__ == "__main__":
    main()
